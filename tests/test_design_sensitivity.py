ROOT = Path(__file__).resolve().parents[1]


def fixture_rows():
    """Complete source-row cohort with the real missingness pattern, synthetic values."""
    rows = []
    missing = {
        (ENDPOINTS[0], "fvt_stress", "31"), (ENDPOINTS[1], "fvt_stress", "31"),
        (ENDPOINTS[2], "ctr", "2.1"), (ENDPOINTS[2], "ctr_stress", "6"),
        (ENDPOINTS[2], "ctr_stress", "7"), (ENDPOINTS[2], "fvt_stress", "11"),
    }
    for g, group in enumerate(GROUPS):
        for j, identifier in enumerate(ID_RANGES[group][0] + ID_RANGES[group][1]):
            row_number = 2 + 10 * g + j
            for e, endpoint in enumerate(ENDPOINTS):
                value = 5 * (e + 1) + g * (e + 2) + 0.6 * (j % 5 - 2) + 0.8 * (j // 5)
                value += (j % 3 - 1) ** 2 * (g + 1) * 0.3
                if endpoint == ENDPOINTS[2]:
                    value *= 10
                absent = (endpoint, group, identifier) in missing
                rows.append(dict(zip(LONG_FIELDS, (
                    "study_ii", "FVT study II", str(row_number), str(e + 3),
                    f"{chr(67 + e)}{row_number}", identifier,
                    composite_mouse_id("study_ii", group, identifier), group, group,
                    endpoint, "immune", "True", "" if absent else value,
                    "missing" if absent else "observed",
                ))))
    return rows


def observed(rows, endpoint, group, block=None, excluded=()):
    return [float(row["value"]) for row in rows
            if row["endpoint"] == endpoint and row["group"] == group
            and row["observation_status"] == "observed" and row["source_id"] not in excluded
            and (block is None or row["source_id"] in ID_RANGES[group][0 if block == "A" else 1])]


class SourceDesignTests(unittest.TestCase):
    def test_literal_mapping_and_no_pool_or_cross_group_assignment(self):
        membership, _ = source_design(fixture_rows())
        self.assertEqual(len(membership), 30)
        self.assertEqual(Counter((r["group"], r["id_range_block"]) for r in membership),
                         Counter({(g, b): 5 for g in GROUPS for b in ("A", "B")}))
        self.assertEqual([sum(r["putative_control_cage_id"] == cage for r in membership)
                          for cage in CONTROL_CAGES], [2, 2, 1, 2, 2, 1])
        self.assertTrue(all(not r["putative_control_cage_id"] for r in membership if r["group"] != "ctr"))
        self.assertTrue(all(r["block_verified"] is False and r["cage_verified"] is False for r in membership))
        for group, identifier in (("ctr", "pool_1"), ("ctr", "1x2"), ("ctr", "01.1"),
                                  ("ctr", "1.10"), ("fvt_stress", "2.1"), ("hkfvt_stress", "14"),
                                  ("ctr_stress", "1.1"), ("ctr", 1.1)):
            with self.subTest(group=group, identifier=identifier), self.assertRaises(ValueError):
                inferred_design(group, identifier)

    def test_missing_altered_duplicate_or_unknown_source_record_fails(self):
        for mutation in ("missing", "altered_id", "duplicate", "unknown", "nonfinite"):
            rows = fixture_rows()
            if mutation == "missing":
                rows.pop(0)
            elif mutation == "altered_id":
                rows[0]["mouse_id"] = "study_ii|ctr|1.2"
            elif mutation == "duplicate":
                rows.append(dict(rows[0]))
            elif mutation == "unknown":
                rows[0]["source_id"] = "pool_1"
            else:
                rows[0]["value"] = math.nan
            with self.subTest(mutation=mutation), self.assertRaises(ValueError):
                source_design(rows)

    def test_selected_prepared_values_and_ids_match_unchanged_source_workbook(self):
        from openpyxl import load_workbook
        from pisa.immune import _read_long

        source = ROOT / "data/raw/source_data.xlsx"
        before = source.read_bytes()
        book = load_workbook(source, read_only=True, data_only=False)
        try:
            iterator = book["FVT study II"].iter_rows(values_only=True)
            headers = next(iterator)
            direct = []
            for source_row, values in enumerate(iterator, 2):
                if all(value is None or value == "" for value in values):
                    continue
                for endpoint in ENDPOINTS:
                    direct.append((values[1], str(values[0]), endpoint, source_row,
                                   values[headers.index(endpoint)]))
        finally:
            book.close()
        prepared = _read_long(ROOT / "data/processed/immune_long.csv")
        membership, _ = source_design(prepared)
        selected = {(r["group"], r["source_id"], r["endpoint"]): r for r in prepared
                    if r["experiment_id"] == "study_ii" and r["endpoint"] in ENDPOINTS}
        self.assertEqual(len(membership), 30)
        self.assertEqual(len(direct), 90)
        for group, identifier, endpoint, row_number, value in direct:
            row = selected[(group, identifier, endpoint)]
            self.assertEqual(int(row["source_row"]), row_number)
            self.assertEqual(row["observation_status"], "missing" if value is None else "observed")
            if value is not None:
                self.assertEqual(float(row["value"]), value)
        self.assertEqual(before, source.read_bytes())


class IndependentModelTests(unittest.TestCase):
    def test_hc3_adjusted_and_unadjusted_contrasts_match_statsmodels(self):
        import numpy as np
        import pandas as pd
        import statsmodels.formula.api as smf

        _, data = source_design(fixture_rows())
        observations = [r for group in GROUPS for r in data[ENDPOINTS[0]][group]
                        if r["observation_status"] == "observed"]
        frame = pd.DataFrame({"value": [r["value"] for r in observations],
                              "group": [r["group"] for r in observations],
                              "block": [r["id_range_block"] for r in observations]})
        for adjusted in (False, True):
            formula = "value ~ C(group, Treatment('ctr'))" + (" + C(block, Treatment('A'))" if adjusted else "")
            reference = smf.ols(formula, frame).fit(cov_type="HC3", use_t=True)
            actual = fit_hc3(observations, adjusted)
            np.testing.assert_allclose(actual["coefficients"], reference.params, atol=1e-12, rtol=1e-12)
            np.testing.assert_allclose(actual["covariance"], reference.cov_params(), atol=1e-12, rtol=1e-12)
            for first, second, vector in (("ctr_stress", "ctr", [0, 1, 0]),
                                           ("fvt_stress", "ctr_stress", [0, -1, 1])):
                contrast = vector + ([0] if adjusted else [])
                expected = reference.t_test(contrast)
                actual_contrast = hc3_contrast(actual, first, second)
                self.assertAlmostEqual(actual_contrast["mean_difference"], float(expected.effect[0]), places=11)
                self.assertAlmostEqual(actual_contrast["standard_error"], float(expected.sd[0, 0]), places=11)
                self.assertAlmostEqual(actual_contrast["t_statistic"], float(expected.tvalue[0, 0]), places=11)
                self.assertAlmostEqual(actual_contrast["p_value"], float(expected.pvalue), places=11)
                self.assertAlmostEqual(actual_contrast["ci_low"], expected.conf_int()[0, 0], places=11)
                self.assertAlmostEqual(actual_contrast["ci_high"], expected.conf_int()[0, 1], places=11)
                self.assertEqual(actual_contrast["degrees_freedom"], reference.df_resid)

    def test_invalid_model_rank_and_group_fail(self):
        same_group = [{"group": "ctr", "id_range_block": "A", "value": float(i)} for i in range(10)]
        with self.assertRaises(ValueError):
            fit_hc3(same_group)
        with self.assertRaises(ValueError):
            fit_hc3([{"group": "pool", "id_range_block": "A", "value": 1}])

    def test_within_block_and_each_multiplicity_family_match_independent_references(self):
        from scipy.stats import ttest_ind
        from statsmodels.stats.multitest import multipletests

        source = fixture_rows()
        tables = calculate(source)
        for key, size in ((OUTPUTS[1], 6), (OUTPUTS[2], 12), (OUTPUTS[4], 6), (OUTPUTS[6], 2)):
            rows = tables[key]
            self.assertEqual(len(rows), size)
            expected = multipletests([r["p_value"] for r in rows], method="fdr_bh")[1]
            self.assertTrue(all(r["bh_family_size"] == size for r in rows))
            for row, q in zip(rows, expected):
                self.assertAlmostEqual(row["q_value"], q, places=13)
        for row in tables[OUTPUTS[2]]:
            a = observed(source, row["endpoint"], row["first_group"], row["id_range_block"])
            b = observed(source, row["endpoint"], row["second_group"], row["id_range_block"])
            expected = ttest_ind(a, b, equal_var=False)
            self.assertAlmostEqual(row["p_value"], expected.pvalue, places=12)
            self.assertAlmostEqual(row["ci_low"], expected.confidence_interval().low, places=11)
            self.assertAlmostEqual(row["ci_high"], expected.confidence_interval().high, places=11)

    def test_equal_cage_weights_define_distinct_estimand_and_correct_unit_counts(self):
        from scipy.stats import ttest_ind

        source = fixture_rows()
        tables = calculate(source)
        for endpoint in ENDPOINTS:
            # Independently aggregate the explicit six literal-ID sets.
            layout = (("1.1", "1.2"), ("2.1", "2.2"), ("3",),
                      ("19.1", "19.2"), ("20.1", "20.2"), ("21",))
            control = {r["source_id"]: float(r["value"]) for r in source
                       if r["endpoint"] == endpoint and r["group"] == "ctr" and r["observation_status"] == "observed"}
            cage_means = [sum(control[key] for key in members if key in control)
                          / sum(key in control for key in members) for members in layout]
            stress = observed(source, endpoint, "ctr_stress")
            row = next(r for r in tables[OUTPUTS[4]] if r["endpoint"] == endpoint and r["second_group"] == "ctr")
            reference = ttest_ind(stress, cage_means, equal_var=False)
            self.assertEqual(row["n_second"], 6)
            self.assertEqual(row["n_putative_control_cages"], 6)
            self.assertEqual(row["n_observed_animals_second"], len(control))
            self.assertAlmostEqual(row["mean_difference"], sum(stress) / len(stress) - sum(cage_means) / 6)
            self.assertNotAlmostEqual(sum(cage_means) / 6, sum(control.values()) / len(control))
            self.assertAlmostEqual(row["p_value"], reference.pvalue, places=12)
        row = next(r for r in tables[OUTPUTS[3]] if r["endpoint"] == ENDPOINTS[2] and r["putative_control_cage_id"] == "2")
        self.assertEqual(row["n_source_animals"], 2)
        self.assertEqual(row["n_observed_animals"], 1)

    def test_all_six_cage_omissions_refit_the_full_original_family(self):
        from scipy.stats import ttest_ind
        from statsmodels.stats.multitest import multipletests

        source = fixture_rows()
        rows = calculate(source)[OUTPUTS[5]]
        self.assertEqual(len(rows), 36)
        for cage, excluded in CONTROL_CAGES.items():
            family = [r for r in rows if r["omitted_putative_control_cage_id"] == cage]
            self.assertEqual(len(family), 6)
            expected_p = []
            for row in family:
                a = observed(source, row["endpoint"], row["first_group"])
                b = observed(source, row["endpoint"], row["second_group"],
                             excluded=excluded if row["second_group"] == "ctr" else ())
                expected_p.append(ttest_ind(a, b, equal_var=False).pvalue)
            expected_q = multipletests(expected_p, method="fdr_bh")[1]
            for row, p, q in zip(family, expected_p, expected_q):
                self.assertAlmostEqual(row["p_value"], p, places=12)
                self.assertAlmostEqual(row["q_value"], q, places=12)
                self.assertEqual(row["bh_family_size"], 6)


class LogAndOutputTests(unittest.TestCase):
    def test_direct_stage_rejects_conflicting_primary_plan_before_outputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for settings in ({"endpoints": list(reversed(ENDPOINTS))},
                             {"confidence_level": 0.90},
                             {"interpretation": "confirmatory"},
                             {"multiple_testing": "none"}):
                with self.subTest(settings=settings), self.assertRaisesRegex(ValueError, "Unsupported fixed immune"):
                    run(root, {"immune": settings})
            self.assertFalse((root / "results").exists())

    def test_log_ratio_matches_scipy_and_reverses(self):
        from scipy.stats import ttest_ind

        first, second = [2, 5, 8, 13, 43], [3, 4, 6, 8]
        actual = positive_log_ratio(first, second)
        reference = ttest_ind([math.log(x) for x in first], [math.log(x) for x in second], equal_var=False)
        self.assertAlmostEqual(actual["p_value"], reference.pvalue, places=13)
        self.assertAlmostEqual(actual["ratio_ci_low"], math.exp(reference.confidence_interval().low), places=12)
        self.assertAlmostEqual(actual["ratio_ci_high"], math.exp(reference.confidence_interval().high), places=12)
        reverse = positive_log_ratio(second, first)
        self.assertAlmostEqual(actual["geometric_mean_ratio"] * reverse["geometric_mean_ratio"], 1)
        self.assertAlmostEqual(actual["ratio_ci_low"] * reverse["ratio_ci_high"], 1)
        for invalid in (0, -1, math.nan, math.inf, True):
            with self.subTest(invalid=invalid), self.assertRaises(ValueError):
                positive_log_ratio([1, 2, invalid], [3, 5, 9])

    def test_stage_outputs_are_lf_repeatable_and_primary_values_unchanged(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "data/processed/immune_long.csv"
            write_csv(source, fixture_rows(), LONG_FIELDS)
            primary = root / "results/tables/immune_contrasts.csv"
            primary.parent.mkdir(parents=True)
            primary.write_bytes(b"primary-output-sentinel\r\n")
            before = source.read_bytes(), primary.read_bytes()
            result = run(root, {})
            self.assertEqual(list(result["table_rows"].values()), [30, 6, 12, 18, 6, 36, 2])
            self.assertFalse(result["verified_block_metadata"])
            self.assertFalse(result["verified_control_cage_metadata"])
            with (root / OUTPUTS[6]).open(encoding="utf-8", newline="") as stream:
                self.assertTrue(all(row["effect_units"] == "geometric-mean ratio (dimensionless)"
                                    for row in csv.DictReader(stream)))
            first = {name: (root / name).read_bytes() for name in OUTPUTS}
            self.assertTrue(all(b"\r" not in value for value in first.values()))
            run(root, {})
            self.assertEqual(first, {name: (root / name).read_bytes() for name in OUTPUTS})
            self.assertEqual(before, (source.read_bytes(), primary.read_bytes()))

    def test_nonpositive_tnf_fails_without_writing_outputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            rows = fixture_rows()
            next(r for r in rows if r["endpoint"] == ENDPOINTS[2] and r["observation_status"] == "observed")["value"] = 0
            write_csv(root / "data/processed/immune_long.csv", rows, LONG_FIELDS)
            with self.assertRaisesRegex(ValueError, "strictly positive"):
                run(root, {})
            self.assertFalse(any((root / name).exists() for name in OUTPUTS))


